assert.equal(categories.length,16,"exactly two rows of eight category tiles required");
assert.match(app,/href="#\/offers"/,"promotional tile must open offers");
assert.match(app,/categoryBySlug\.get\(slug\)/,"tiles must resolve actual category records");
assert.match(app,/state\.categories\.filter/,"categories should come from live database");
assert.match(app,/categoryChain\(c\.id\)/,"hidden or inactive parent categories must not leak");
assert.match(app,/data-parent-id/,"category hierarchy must be preserved in tiles");
assert.match(app,/href="#\/categories\/'\+encodeURIComponent\(item\.id\)/,"clicking a category must open its own catalog");
assert.match(app,/function descendantIds\(/,"catalog must include nested products");
assert.match(app,/categoryChain\(p\.category_id\)/,"inactive ancestors must hide associated products");
assert.match(app,/if\(route==="categories"&&parts\[1\]\)/,"linked category routes must survive reloading");
assert.match(app,/const matchCat=!category\|\|descendants\.has/,"product filtering must use category IDs");
assert.doesNotMatch(app,/data-home-category-group/,"unrequested category tabs must not appear");
assert.match(app,/function categoryPhoto\(/,"photographic category image missing");
assert.doesNotMatch(app,/class="category-emoji"/,"emoji placeholders are not approved product photos");
assert.match(app,/category-image-missing/,"new categories without photos require a neutral fallback");
assert.match(admin,/name="categoryPhoto"/,"category photo upload must remain editable");
assert.match(admin,/booleanSelect\("إظهاره في الصفحة الرئيسية","show_on_home"/,"category visibility control missing");
assert.match(admin,/function categoryAncestors\(/,"administrator must preserve category hierarchy");
assert.match(admin,/categoryAncestors\(parent,rows\)/,"self-referential category parents should be rejected");
assert.match(css,/\.bazoo-category-grid\{[\s\S]*?grid-template-columns:repeat\(8,minmax\(0,1fr\)\)/,"desktop should render 8 columns");
assert.match(css,/grid-template-rows:none!important/,"home category grid should flow into as many rows as needed");
assert.match(css,/\.bazoo-category-circle/,"rounded imagery missing");
assert.match(css,/\.bazoo-category-circle \.category-thumb/,"photograph treatment missing");
assert.match(css,/BAZOO v49/,"compact responsive category gallery must be present");
assert.match(css,/\.bazoo-category-scroller\{[\s\S]*?overflow-x:visible!important/,"mobile category gallery must not require sideways scrolling");
assert.match(css,/\.bazoo-category-grid\{[\s\S]*?grid-template-columns:repeat\(4,minmax\(0,1fr\)\)!important/,"mobile category gallery must use four balanced columns");
assert.match(css,/\.bazoo-category-circle\{[\s\S]*?clamp\(65px,19vw,82px\)/,"mobile circles must remain compact and legible");
assert.match(css,/\.bazoo-category-title\{[\s\S]*?font-size:10.5px!important/,"mobile category labels must fit four columns");
assert.match(html,/style\.css\?v=20261123circles49/,"stylesheet cache must be refreshed");
assert.match(html,/bundle\.js\?v=20261123names47/,"JavaScript cache must be refreshed");
assert.match(adminHtml,/admin-panel\.js\?v=20261123names47/,"management portal must remain intact");

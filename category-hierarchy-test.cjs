const assert=require("node:assert/strict");
const fs=require("node:fs");
const app=fs.readFileSync("app.js","utf8");
const admin=fs.readFileSync("admin-panel.js","utf8");
const css=fs.readFileSync("style.css","utf8");
const html=fs.readFileSync("index.html","utf8");
const adminHtml=fs.readFileSync("admin.html","utf8");
const layout=app.match(/const homeCategoryOrder=\[([\s\S]*?)\];/);
assert.ok(layout,"approved category display order missing");
const categories=JSON.parse("["+layout[1]+"]");
const expected=["offers","phones","screens","tablets","devices-games","laptops","headphones","smart-watches","heaters","washing-machines","refrigerators","air-conditioners","cookers","cooking-appliances","vacuum-cleaners","perfumes"];
assert.deepEqual(categories,expected,"2 rows must match supplied screenshot, right to left");
assert.equal(categories.length,16,"exactly two rows of eight category tiles required");
assert.match(app,/href="#\/offers"/,"promotional tile must open offers");
assert.match(app,/categoryBySlug\.get\(slug\)/,"tiles must resolve actual category records");
assert.match(app,/state\.categories\.filter/,"categories should come from live database");
assert.match(app,/categoryChain\(c\.id\)/,"hidden or inactive parent categories must not leak");
assert.match(app,/data-parent-id/,"category hierarchy must be preserved in tiles");
assert.match(app,/href="#\/categories\/'\+encodeURIComponent\(item\.id\)/,"clicking a category must open its own catalog");
assert.match(app,/function descendantIds\(/,"catalog must include nested products");
assert.match(app,/categoryChain\(p\.category_id\)/,"inactive ancestors must hide associated products");
assert.match(app,/if\(route==="categories"&&parts\[1\]\)/,"linked category routes must survive reloading");
assert.match(app,/const matchCat=!category\|\|descendants\.has/,"product filtering must use category IDs");
assert.doesNotMatch(app,/data-home-category-group/,"unrequested category tabs must not appear");
assert.match(app,/function categoryPhoto\(/,"photographic category image missing");
assert.doesNotMatch(app,/class="category-emoji"/,"emoji placeholders are not approved product photos");
assert.match(app,/category-image-missing/,"new categories without photos require a neutral fallback");
assert.match(admin,/name="categoryPhoto"/,"category photo upload must remain editable");
assert.match(admin,/booleanSelect\("إظهاره في الصفحة الرئيسية","show_on_home"/,"category visibility control missing");
assert.match(admin,/function categoryAncestors\(/,"administrator must preserve category hierarchy");
assert.match(admin,/categoryAncestors\(parent,rows\)/,"self-referential category parents should be rejected");
// The homepage must show a fixed two-row carousel in both mobile and desktop contexts.
const carouselStyles=css.slice(css.lastIndexOf("/* BAZOO v51"));
assert.match(carouselStyles,/BAZOO v51/,"two-row category carousel CSS is missing");
assert.match(carouselStyles,/grid-auto-flow:column!important/,"category items must fill rows before adding columns");
assert.match(carouselStyles,/grid-template-rows:repeat\(2,minmax\(121px,auto\)\)!important/,"desktop categories must show exactly two rows");
assert.match(carouselStyles,/grid-template-rows:repeat\(2,minmax\(109px,auto\)\)!important/,"mobile categories must show exactly two rows");
assert.match(carouselStyles,/grid-auto-columns:132px!important/,"laptop must show a consistent scrollable column width");
assert.match(carouselStyles,/grid-auto-columns:clamp\(83px,24vw,96px\)!important/,"mobile must show compact consistent columns");
assert.match(carouselStyles,/overflow-x:auto!important/,"carousel should scroll horizontally at every breakpoint");
assert.match(carouselStyles,/scroll-snap-type:x proximity/,"category horizontal scroll should settle on a column");
assert.match(carouselStyles,/touch-action:pan-x pan-y/,"mobile must support touch swipe gestures");
assert.doesNotMatch(carouselStyles,/grid-template-columns:repeat\([345678],minmax\(0,1fr\)\)!important/,"categories should not wrap to extra rows at different screen widths");
assert.match(app,/class="bazoo-category-scroll-controls"/,"desktop needs visible navigation arrows");
assert.match(app,/data-category-scroll="1"/,"right arrow is missing");
assert.match(app,/data-category-scroll="-1"/,"left arrow is missing");
assert.match(app,/rail\.scrollBy\(\{left:Number\(b\.dataset\.categoryScroll\)\*step/,"arrow buttons must scroll the gallery");
assert.match(app,/class="bazoo-category-scroller" dir="rtl"/,"category scroll direction must match the Arabic RTL layout");
assert.match(css,/\.bazoo-category-circle \.category-thumb/,"photograph treatment missing");
assert.match(html,/style\.css\?v=20261123twoRows51/,"stylesheet cache must be refreshed");
assert.match(html,/bundle\.js\?v=20261123twoRows51/,"JavaScript cache must be refreshed");
assert.match(adminHtml,/admin-panel\.js\?v=20261123preview50/,"management portal must remain intact");
